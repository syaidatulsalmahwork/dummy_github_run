def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

def power(a, b):
    return a ** b

print(f"add(2, 3) = {add(2, 3)}")
print(f"subtract(10, 4) = {subtract(10, 4)}")
print(f"multiply(6, 7) = {multiply(6, 7)}")
print(f"divide(20, 5) = {divide(20, 5)}")
print(f"power(2, 8) = {power(2, 8)}")
